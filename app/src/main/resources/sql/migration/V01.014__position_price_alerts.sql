-- Two notification-only rules per open equity/ETF, with durable crossing state.
CREATE TABLE investory.position_price_alert (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  portfolio_id bigint NOT NULL REFERENCES investory.portfolios(id) ON DELETE CASCADE,
  asset_id bigint NOT NULL REFERENCES investory.assets(id),
  side varchar(8) NOT NULL CHECK (side IN ('LOSS', 'PROFIT')),
  mode varchar(8) NOT NULL DEFAULT 'PERCENT' CHECK (mode IN ('PERCENT', 'PRICE')),
  threshold numeric(20,8) NOT NULL DEFAULT 10 CHECK (threshold > 0),
  action_text varchar(240) NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  initialized boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT false,
  incident_sequence bigint NOT NULL DEFAULT 0 CHECK (incident_sequence >= 0),
  last_reference_price numeric(20,8),
  last_observed_price numeric(20,8),
  last_observed_at timestamptz,
  last_alert_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_position_price_alert UNIQUE (portfolio_id, asset_id, side)
);
CREATE INDEX idx_position_price_alert_active ON investory.position_price_alert(portfolio_id, enabled, asset_id);
