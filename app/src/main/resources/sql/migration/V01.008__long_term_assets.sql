    archived_at date,
    notes text,
    external_key varchar(128),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(name) <> '')
);
CREATE INDEX ix_real_estate_portfolio_active ON investory.real_estate(portfolio_id, archived_at);
COMMENT ON COLUMN investory.real_estate.tax_base IS
    'Annual rental-tax base. Annual rental tax = tax_base * 0.085.';
CREATE UNIQUE INDEX ux_real_estate_portfolio_land_register
    ON investory.real_estate(portfolio_id, land_register_number)
    WHERE land_register_number IS NOT NULL AND btrim(land_register_number) <> '';
CREATE UNIQUE INDEX ux_real_estate_portfolio_external_key ON investory.real_estate(portfolio_id, external_key)
    WHERE external_key IS NOT NULL;

