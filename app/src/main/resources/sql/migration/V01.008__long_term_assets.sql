CREATE TABLE investory.rental_contract (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    real_estate_id bigint NOT NULL REFERENCES investory.real_estate(id) ON DELETE CASCADE,
    start_date date NOT NULL,
    end_date date,
    terminated_date date,
    bootstrap_managed boolean NOT NULL DEFAULT false,
    tenant_name varchar(200),
    tenant_email varchar(320),
    tenant_phone varchar(50),
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date IS NULL OR end_date >= start_date),
    CHECK (terminated_date IS NULL OR terminated_date >= start_date)
);
CREATE INDEX ix_rental_contract_real_estate_dates ON investory.rental_contract(real_estate_id, start_date DESC);

CREATE TABLE investory.rental_contract_term (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_contract_id bigint NOT NULL REFERENCES investory.rental_contract(id) ON DELETE CASCADE,
    cash_flow_type varchar(32) NOT NULL CHECK (cash_flow_type IN
        ('RENT', 'PARKING_RENT', 'ADMIN_FEE', 'UTILITIES', 'PROPERTY_TAX', 'INSURANCE', 'OTHER_INCOME', 'OTHER_EXPENSE')),
    amount numeric(30,12) NOT NULL CHECK (amount >= 0),
    frequency varchar(16) NOT NULL CHECK (frequency IN ('MONTHLY', 'ANNUAL')),
    paid_by_tenant boolean NOT NULL DEFAULT false,
    UNIQUE (rental_contract_id, cash_flow_type)
);
CREATE INDEX ix_rental_contract_term_contract ON investory.rental_contract_term(rental_contract_id, cash_flow_type);

CREATE TABLE investory.real_estate_valuation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    real_estate_id bigint NOT NULL REFERENCES investory.real_estate(id) ON DELETE CASCADE,
    valuation_date date NOT NULL,
    value numeric(30,12) NOT NULL CHECK (value >= 0),
    UNIQUE (real_estate_id, valuation_date)
);
CREATE INDEX ix_real_estate_valuation_dates ON investory.real_estate_valuation(real_estate_id, valuation_date DESC);

