CREATE SEQUENCE investory.long_term_asset_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

CREATE TABLE investory.long_term_asset_history (
    asset_id bigint NOT NULL,
    asset_type character varying(32) NOT NULL,
    complete boolean DEFAULT false NOT NULL,
    CONSTRAINT ck_long_term_asset_history_type CHECK (((asset_type)::text = ANY ((ARRAY['REAL_ESTATE'::character varying, 'BOND'::character varying, 'CASH_RESERVE'::character varying, 'PERSONAL_ASSET'::character varying])::text[]))),
    CONSTRAINT long_term_asset_history_pkey PRIMARY KEY (asset_id)
);

CREATE TABLE investory.long_term_asset_archive_interval (
    id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME investory.long_term_asset_archive_interval_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1) NOT NULL,
    asset_id bigint NOT NULL,
    archived_from date NOT NULL,
    archived_to date,
    CONSTRAINT ck_long_term_asset_archive_interval_dates CHECK (((archived_to IS NULL) OR (archived_to >= archived_from))),
