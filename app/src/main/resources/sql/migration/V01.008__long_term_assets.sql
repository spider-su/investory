CREATE VIEW investory.app_v_long_term_assets AS
 SELECT bond.id,
    bond.portfolio_id,
    'BOND'::text AS asset_type,
    bond.name,
    bond.currency,
    bond.value AS current_value,
    bond.acquisition_date,
    bond.archived_at
   FROM investory.bond
UNION ALL
 SELECT real_estate.id,
    real_estate.portfolio_id,
    'REAL_ESTATE'::text AS asset_type,
    real_estate.name,
    real_estate.currency,
    real_estate.value AS current_value,
    real_estate.acquisition_date,
    real_estate.archived_at
   FROM investory.real_estate
UNION ALL
 SELECT cash_reserve.id,
    cash_reserve.portfolio_id,
    'CASH_RESERVE'::text AS asset_type,
    cash_reserve.name,
    cash_reserve.currency,
    cash_reserve.value AS current_value,
    cash_reserve.acquisition_date,
    cash_reserve.archived_at
   FROM investory.cash_reserve
UNION ALL
 SELECT personal_asset.id,
    personal_asset.portfolio_id,
    'PERSONAL_ASSET'::text AS asset_type,
    personal_asset.name,
    personal_asset.currency,
    personal_asset.value AS current_value,
    personal_asset.acquisition_date,
    personal_asset.archived_at
   FROM investory.personal_asset;

CREATE VIEW investory.recon_v_long_term_assets AS
 WITH asset_ids AS (
         SELECT real_estate.id,
            real_estate.portfolio_id
           FROM investory.real_estate
        UNION ALL
         SELECT bond.id,
            bond.portfolio_id
           FROM investory.bond
        UNION ALL
         SELECT cash_reserve.id,
            cash_reserve.portfolio_id
           FROM investory.cash_reserve
        UNION ALL
         SELECT personal_asset.id,
            personal_asset.portfolio_id
           FROM investory.personal_asset
        ), duplicate_ids AS (
         SELECT asset_ids.id,
            min(asset_ids.portfolio_id) AS portfolio_id,
            count(*) AS occurrences
           FROM asset_ids
          GROUP BY asset_ids.id
         HAVING (count(*) > 1)
        ), orphan_contracts AS (
         SELECT c.id,
            c.real_estate_id AS asset_id
           FROM investory.rental_contract c
          WHERE (NOT (EXISTS ( SELECT 1
                   FROM investory.real_estate r
                  WHERE (r.id = c.real_estate_id))))
        )
 SELECT 'LT_ASSET_ID_COLLISION'::text AS issue_code,
    duplicate_ids.id AS asset_id,
    duplicate_ids.portfolio_id,
    'same id occurs in multiple explicit asset tables'::text AS details
   FROM duplicate_ids
UNION ALL
 SELECT 'LT_RENTAL_CONTRACT_ORPHAN'::text AS issue_code,
    orphan_contracts.asset_id,
    NULL::bigint AS portfolio_id,
    'rental contract has no real-estate parent'::text AS details
   FROM orphan_contracts;

