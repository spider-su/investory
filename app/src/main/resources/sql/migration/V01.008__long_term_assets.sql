    CONSTRAINT bond_interest_rate_check CHECK ((interest_rate >= (0)::numeric)),
    CONSTRAINT bond_name_check CHECK ((btrim((name)::text) <> ''::text)),
    CONSTRAINT bond_value_check CHECK ((value >= (0)::numeric)),
    CONSTRAINT ck_bond_maturity_after_acquisition CHECK (((acquisition_date IS NULL) OR (maturity_date >= acquisition_date))),
    CONSTRAINT bond_pkey PRIMARY KEY (id),
    CONSTRAINT bond_currency_fkey FOREIGN KEY (currency) REFERENCES investory.currencies(id),
    CONSTRAINT bond_portfolio_id_fkey FOREIGN KEY (portfolio_id) REFERENCES investory.portfolios(id) ON DELETE CASCADE
